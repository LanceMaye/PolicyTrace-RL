"""Qwen completion -> native tau2 messages, preserving batch order and routing IDs.

Parse ONLY the generated assistant suffix, never the rendered prompt containing
instructional tool_call examples. IDs are generated by the caller's unique turn
namespace; they are absent from Qwen's text protocol and must live in the ledger.
"""
import json
import re

import policytrace.stage0  # Configure pinned local tau2 before importing it.
from tau2.data_model.message import AssistantMessage, MultiToolMessage, ToolCall, ToolMessage


def _unique_object(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError('Duplicate JSON key')
        result[key] = value
    return result


def parse_completion(text, validators, turn_namespace, *, reject_mixed=False):
    """Strict, non-streaming parser; preserve mixed content for explicit validation.

    Accept the training suffix's optional terminal im_end and newline. Validate
    every call against the unchanged Fork schema before any side effects occur.
    This does not validate business policy or guarantee runtime preconditions.
    """
    if not re.fullmatch(r'[A-Za-z0-9_-]+', turn_namespace):
        raise ValueError('Invalid turn namespace')
    text = text.rstrip()
    if text.endswith('<|im_end|>'):
        text = text[:-len('<|im_end|>')].rstrip()
    if '<|' in text or '<tool_response>' in text or '</tool_response>' in text:
        raise ValueError('Unexpected control or tool response token')
    calls, content, remaining = [], [], text
    while '<tool_call>' in remaining:
        prefix, remaining = remaining.split('<tool_call>', 1)
        if '</tool_call>' in prefix:
            raise ValueError('Orphan closing tag')
        content.append(prefix)
        if '</tool_call>' not in remaining:
            raise ValueError('Truncated tool call')
        body, remaining = remaining.split('</tool_call>', 1)
        if '<tool_call>' in body:
            raise ValueError('Nested tool call')
        fn = json.loads(body, object_pairs_hook=_unique_object,
                        parse_constant=lambda x: (_ for _ in ()).throw(ValueError('Nonfinite JSON')))
        if not isinstance(fn, dict) or set(fn) != {'name', 'arguments'}:
            raise ValueError('Invalid function envelope')
        if not isinstance(fn['name'], str) or fn['name'] not in validators:
            raise ValueError('Unknown tool')
        if not isinstance(fn['arguments'], dict):
            raise ValueError('Arguments must be an object')
        validators[fn['name']].validate(fn['arguments'])
        calls.append(ToolCall(id=f'{turn_namespace}_{len(calls)}', name=fn['name'], arguments=fn['arguments']))
    if '</tool_call>' in remaining or '<tool_call' in remaining or '</tool_call' in remaining:
        raise ValueError('Malformed tool delimiter')
    content.append(remaining)
    prose = ''.join(content).strip()
    if reject_mixed and prose and calls:
        raise ValueError('Mixed text and tool calls are forbidden by strict Fork communication')
    result = AssistantMessage(role='assistant', content=prose or None, tool_calls=calls or None)
    result.validate()
    return result


def validate_observations(message, observations):
    """Native replay requires result order AND ID to match the Assistant batch."""
    calls = message.tool_calls or []
    ids = [c.id for c in calls]
    if len(ids) != len(set(ids)) or len(calls) != len(observations):
        raise ValueError('Duplicate ID or missing observation')
    for call, observation in zip(calls, observations):
        if not isinstance(observation, ToolMessage) or observation.id != call.id or observation.requestor != call.requestor:
            raise ValueError('Observation routing mismatch')


def execute_batch(environment, message):
    """Minimal sequential adapter matching Orchestrator.step (not a transaction).

    Production orchestration should reuse the Fork. This small path verifies the
    interface contract only; max_errors/termination are tested on the real Fork.
    """
    if not message.tool_calls or any(c.requestor != 'assistant' for c in message.tool_calls):
        raise ValueError('Expected nonempty assistant batch')
    if len({c.id for c in message.tool_calls}) != len(message.tool_calls):
        raise ValueError('Duplicate call IDs')
    results = [environment.get_response(c) for c in message.tool_calls]
    validate_observations(message, results)
    return MultiToolMessage(role='tool', tool_messages=results)


def context_batch(message, observations):
    """Student-visible batch; native trajectory separately retains timestamps/errors."""
    validate_observations(message, observations)
    assistant = {'role': 'assistant', 'content': message.content or '', 'tool_calls': [
        {'id': c.id, 'type': 'function', 'function': {'name': c.name, 'arguments': c.arguments}}
        for c in message.tool_calls]}
    return [assistant] + [{'role': 'tool', 'name': c.name, 'tool_call_id': result.id,
                           'content': result.content}
                          for c, result in zip(message.tool_calls, observations)]
