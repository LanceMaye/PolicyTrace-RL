"""Build Stage 1 records from two saved Stage 0 episodes; zero API requests."""
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path

from policytrace.evaluation.schema import (ArtifactReference, CostObservation, EpisodeRecord, EvaluationPlan,
    ResourceUsage, RunContext, SamplingSettings, TokenUsage, ToolStatistics, task_set_hash)
from policytrace.rewards.official import evaluate_r0
from policytrace.stage0.task_loader import iter_retail_records, load_retail_task
from policytrace.stage0.db_adapter import load_retail_db
from tau2.data_model.simulation import SimulationRun
from loguru import logger

TASKS = ('retail_131', 'retail_152')


def artifact(path: Path) -> ArtifactReference:
    return ArtifactReference(path=path.as_posix(), sha256=hashlib.sha256(path.read_bytes()).hexdigest())


def usage_for(simulation: SimulationRun, role: str) -> TokenUsage:
    messages = [(i, m) for i, m in enumerate(simulation.messages) if m.role == role]
    # The initial greeting is generated by the orchestrator, not a model.
    generated = [m for i, m in messages if not (i == 0 and role == 'assistant')]
    if not generated or any(getattr(m, 'usage', None) is None for m in generated):
        return TokenUsage(missing_reason='Provider usage is missing on one or more generated messages')
    return TokenUsage(prompt_tokens=sum(m.usage['prompt_tokens'] for m in generated),
                      completion_tokens=sum(m.usage['completion_tokens'] for m in generated),
                      source='provider_usage', missing_reason=None)


def main() -> None:
    out = Path('data/private/stage1')
    out.mkdir(parents=True, exist_ok=True)
    logger.remove()
    logger.add(out / 'replay.log', level='INFO')
    old = Path('data/private/stage0/deepseek')
    saved = json.loads(Path('reports/stage0/deepseek_results.json').read_text(encoding='utf-8'))
    ledger = json.loads((old / 'cost_ledger.json').read_text(encoding='utf-8'))
    settings = SamplingSettings(temperature=saved['temperature'], max_output_tokens=saved['max_output_tokens'],
                                thinking=saved['thinking'], provider_seed_supported=False)
    config_id = hashlib.sha256(json.dumps({'settings': settings.model_dump(),
        'fingerprints': saved['system_fingerprints'], 'fork': 'e33e9511e4f51e5cfa16e12b02d0e4ab327b5887'}, sort_keys=True).encode()).hexdigest()
    context = RunContext(run_id='stage1-replay-of-stage0', task_set_id='stage0-two-live-episodes-diagnostic-only',
        task_set_sha256=task_set_hash(TASKS), environment_sha='e33e9511e4f51e5cfa16e12b02d0e4ab327b5887',
        dataset_revision='86971dc03da6e7c1a7933295e05b84aab8215386', model_id=saved['model'],
        model_version=';'.join(saved['system_fingerprints']), model_sampling=settings,
        simulator_model=saved['model'], simulator_version=';'.join(saved['system_fingerprints']),
        simulator_config_id=config_id, simulator_sampling=settings,
        harness_version='tau2-official-orchestrator@e33e9511e4f51e5cfa16e12b02d0e4ab327b5887',
        max_steps=saved['max_steps_per_episode'], max_errors=1,
        unrecorded_fields=('model_checkpoint: remote service alias', 'max_context_tokens: only a byte cap was recorded'))
    plan = EvaluationPlan(context=context, task_ids=TASKS, trial_ids=('0',), trials_per_task=1, provenance='saved_real_episode')
    tasks = {raw['id']: load_retail_task(raw, index) for index, raw in iter_retail_records(Path('data/raw')) if raw['id'] in TASKS}
    episodes = []
    evidence = []
    for task_id in TASKS:
        source = old / f'{task_id}-episode.json'
        simulation = SimulationRun.model_validate_json(source.read_text(encoding='utf-8'))
        record = tasks[task_id]
        snapshot = load_retail_db(record.db_path, Path('data/raw'))
        result = evaluate_r0(record, snapshot, simulation, private_reward_path=out / f'{task_id}-official-reward.json')
        previous = json.loads((old / f'{task_id}-reward.json').read_text(encoding='utf-8'))
        if result.reward_info().model_dump(mode='json') != previous:
            raise RuntimeError('Offline official result differs from the saved Stage 0 result')
        student, user = usage_for(simulation, 'assistant'), usage_for(simulation, 'user')
        costs = []
        for role, usage in [('student', student), ('user', user)]:
            if usage.prompt_tokens is not None and usage.completion_tokens is not None:
                cost = (usage.prompt_tokens * ledger['input_peak_cache_miss_cny_per_m'] +
                        usage.completion_tokens * ledger['output_peak_cny_per_m']) / 1e6
                costs.append(CostObservation(role=role, amount=cost, currency='CNY', kind='upper_bound_estimate',
                                             source='archived-stage0-provider-usage-and-peak-prices-2026-10-09'))
        calls = [c for m in simulation.messages for c in (getattr(m, 'tool_calls', None) or [])]
        responses = [m for m in simulation.messages if m.role == 'tool']
        if sorted(c.id for c in calls) != sorted(m.id for m in responses):
            raise RuntimeError('Saved tool calls and responses are incomplete')
        diagnostics = ('COUNTRY_STRING_MISMATCH_CONFIRMED_OFFLINE',) if task_id == 'retail_131' else ('SIMULATOR_EARLY_DISCLOSURE_MANUAL_REVIEW',)
        episode = EpisodeRecord(context=context, episode_id=simulation.id, task_id=task_id, trial_id='0', provenance='saved_real_episode',
            db_snapshot_id=record.db_path, db_snapshot_sha256=snapshot.file_sha256, seed=simulation.seed,
            evaluated_at=datetime.now(timezone.utc), original_timestamp=simulation.timestamp,
            termination_reason=simulation.termination_reason.value, execution_status='completed', scoring_status='scored',
            official_score=result.score, trajectory=artifact(source), duration_seconds=simulation.duration,
            tools=ToolStatistics(attempted=len(calls), attempt_scope='parsed_calls',
                                 execution_errors=sum(bool(m.error) for m in responses),
                                 missing_reason='Stage 0 did not log malformed tool attempts or classify framework errors'),
            resources=ResourceUsage(student=student, user=user, api_costs=tuple(costs) if len(costs) == 2 else None),
            diagnostic_codes=diagnostics)
        episodes.append(episode)
        evidence.append({'task_id': task_id, 'official_reward': result.score.official_reward,
                         'raw_reward_matches_stage0': True, 'trajectory_sha256': episode.trajectory.sha256})
    prompt_sum = sum(e.resources.student.prompt_tokens + e.resources.user.prompt_tokens for e in episodes)
    completion_sum = sum(e.resources.student.completion_tokens + e.resources.user.completion_tokens for e in episodes)
    if (prompt_sum, completion_sum) != (saved['total_prompt_tokens'], saved['total_completion_tokens']):
        raise RuntimeError('Message provider usage differs from Stage 0 cumulative usage')
    (out / 'plan.json').write_text(plan.model_dump_json(indent=2), encoding='utf-8')
    (out / 'episodes.jsonl').write_text('\n'.join(e.model_dump_json() for e in episodes) + '\n', encoding='utf-8')
    public = {'status': 'PASS', 'scope': 'offline replay of saved episodes; not new rollouts or a benchmark',
              'api_calls': 0, 'new_api_cost': 0, 'episodes': evidence, 'provider_usage_matches_stage0': True,
              'private_plan': str(out / 'plan.json'), 'private_records': str(out / 'episodes.jsonl')}
    Path('reports/stage1').mkdir(parents=True, exist_ok=True)
    Path('reports/stage1/replay_evidence.json').write_text(json.dumps(public, indent=2) + '\n', encoding='utf-8')
    print(json.dumps(public))


if __name__ == '__main__':
    main()
